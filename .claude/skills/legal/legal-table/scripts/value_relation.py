ROLE_DOMAIN = ("기준", "허용", "상한", "기본")

# 근거 종류이자 강도. 순서가 강한 것 → 약한 것이다.
# 정본은 contract/outputs.json 의 `relation_basis$강도` 이며 여기는 실행 도메인이다.
BASIS_DOMAIN = ("동일줄_직접수식", "동일줄_순서대응")
BASIS_WEAK = ("동일줄_순서대응",)


def _key(rec):
    return (rec["source_file"].rsplit("/", 1)[-1], rec["line"],
            rec["surface_offset"][0])


def apply(quarantine, values=()):
    """격리 레코드에 relation_* 를 채운다. 부작용으로 in-place 갱신한다.

    발급표·미발급표의 키가 원문에서 사라지면 조용히 넘어가지 않고 예외를 낸다.
    원문이 바뀌었는데 판정표가 그대로면 판정이 실효한 것이므로 드러나야 한다.

    짝은 확정·격리 양쪽에서 찾는다. **가장 쓸모 있는 짝이 바로 그 경계에 있다** —
    행당 L64 는 기준 200 이 비교표현이 없어 격리됐고 허용 330 은 `이하` 가 붙어
    확정으로 갔다. 격리 안에서만 짝을 찾으면 이 관계를 잇지 못한다. 짝 방향은
    격리 → 확정 한 방향이며, 확정 레코드에는 아무 필드도 쓰지 않는다.
    """
    by_key = {}
    for rec in list(quarantine) + list(values):
        by_key.setdefault(_key(rec)[:2], []).append(rec)

    unseen_issue = set(ISSUE)
    unseen_withhold = set(WITHHELD)

    for rec in quarantine:
        k = _key(rec)
        if k in ISSUE:
            unseen_issue.discard(k)
            role, pair_off, quote, basis_note, basis = ISSUE[k]
            if basis not in BASIS_DOMAIN:
                raise ValueError(
                    f"{rec['value_id']} basis 가 값 도메인 밖이다: {basis!r}. "
                    "새 근거 종류가 생겼으면 계약을 먼저 갱신한다")
            if quote not in rec["line_text"]:
                raise ValueError(
                    f"{rec['value_id']} 근거발췌가 원문에 없다: {quote!r}")
            pair_id = None
            if pair_off is not None:
                cand = [r for r in by_key[k[:2]]
                        if r["surface_offset"][0] == pair_off]
                if not cand:
                    raise ValueError(
                        f"{rec['value_id']} 짝 offset {pair_off} 에 레코드가 "
                        "없다. 원문이 바뀌었으면 판정표를 다시 본다")
                pair_id = cand[0]["value_id"]
            rec["relation_role"] = role
            rec["relation_basis"] = basis
            rec["relation_quote"] = quote
            rec["relation_note"] = basis_note
            rec["relation_pair"] = pair_id
            rec["relation_reason"] = None
        else:
            if k in WITHHELD:
                unseen_withhold.discard(k)
                cls, note = WITHHELD[k]
            else:
                cls, note = "수식어어휘없음", None
            rec["relation_role"] = None
            rec["relation_basis"] = None
            rec["relation_quote"] = None
            rec["relation_note"] = note
            rec["relation_pair"] = None
            rec["relation_reason"] = cls

    if unseen_issue or unseen_withhold:
        raise ValueError(
            f"판정표 키가 격리에서 사라졌다 — 발급 {sorted(unseen_issue)} · "
            f"미발급 {sorted(unseen_withhold)}. 원문이 바뀌었으면 판정을 다시 한다")
    return quarantine


